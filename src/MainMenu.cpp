static const int FONT_CHARS = 95, FONT_CW = 8, FONT_CH = 8;
static const int FONT_COLS = 16, FONT_ROWS = 6;

// Helper: compute NDC width of a string at given scale
static float textWidthNDC(const std::string &text, float scale, float screenW)
{
    float cw = (FONT_CW * scale) / screenW * 2.0f;
    int maxLen = 0, curLen = 0;
    for (char c : text) {
        if (c == '\n') { if (curLen > maxLen) maxLen = curLen; curLen = 0; }
        else curLen++;
    }
    if (curLen > maxLen) maxLen = curLen;
    return maxLen * cw;
}

MainMenu::MainMenu(float screenWidth, float screenHeight)
    : overlayShader("../res/shaders/overlay.vert", "../res/shaders/overlay.frag"),
      bgVAO(0), bgVBO(0), textVAO(0), textVBO(0), fontTexture(0),
      screenW(screenWidth), screenH(screenHeight), animTime(0.0f)
{
    glGenVertexArrays(1, &bgVAO); glGenBuffers(1, &bgVBO);
    glBindVertexArray(bgVAO);
    glBindBuffer(GL_ARRAY_BUFFER, bgVBO);
    glBufferData(GL_ARRAY_BUFFER, 16 * sizeof(float), nullptr, GL_DYNAMIC_DRAW);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4*sizeof(float), (void*)0);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4*sizeof(float), (void*)(2*sizeof(float)));
    glEnableVertexAttribArray(1);
    glBindVertexArray(0);

    glGenVertexArrays(1, &textVAO); glGenBuffers(1, &textVBO);
    glBindVertexArray(textVAO);
    glBindBuffer(GL_ARRAY_BUFFER, textVBO);
    glBufferData(GL_ARRAY_BUFFER, 8192 * sizeof(float), nullptr, GL_DYNAMIC_DRAW);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4*sizeof(float), (void*)0);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4*sizeof(float), (void*)(2*sizeof(float)));
    glEnableVertexAttribArray(1);
    glBindVertexArray(0);

    initFont();

    // Centered buttons
    float btnW = 0.40f, btnH = 0.12f;
    float btnX = -btnW / 2.0f;
    playBtn = { btnX, 0.00f, btnW, btnH, "START", 0.1f, 0.6f, 1.0f, 0.0f, false };
    quitBtn = { btnX, -0.20f, btnW, btnH, "QUIT", 0.8f, 0.2f, 0.25f, 0.0f, false };
}

MainMenu::~MainMenu()
{
    glDeleteVertexArrays(1, &bgVAO); glDeleteBuffers(1, &bgVBO);
    glDeleteVertexArrays(1, &textVAO); glDeleteBuffers(1, &textVBO);
    glDeleteTextures(1, &fontTexture);
}

void MainMenu::initFont()
{
    int aw = FONT_COLS * FONT_CW, ah = FONT_ROWS * FONT_CH;
    std::vector<unsigned char> px(aw * ah, 0);
    for (int c = 0; c < FONT_CHARS; c++) {
        int col = c % FONT_COLS, row = c / FONT_COLS;
        for (int y = 0; y < FONT_CH; y++) {
            unsigned char bits = font8x8[c][y];
            for (int x = 0; x < FONT_CW; x++)
                if (bits & (0x80 >> x))
                    px[(row*FONT_CH+y)*aw + col*FONT_CW+x] = 255;
        }
    }
    glGenTextures(1, &fontTexture);
    glBindTexture(GL_TEXTURE_2D, fontTexture);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_R8, aw, ah, 0, GL_RED, GL_UNSIGNED_BYTE, px.data());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glBindTexture(GL_TEXTURE_2D, 0);
}

void MainMenu::drawRect(float x, float y, float w, float h, float r, float g, float b, float a)
{
    float v[] = { x,y,0,0, x+w,y,0,0, x+w,y+h,0,0, x,y+h,0,0 };
    overlayShader.setUniform1i("u_useTexture", 0);
    overlayShader.setUniform4f("u_color", r, g, b, a);
    glBindVertexArray(bgVAO);
    glBindBuffer(GL_ARRAY_BUFFER, bgVBO);
    glBufferSubData(GL_ARRAY_BUFFER, 0, sizeof(v), v);
    glDrawArrays(GL_TRIANGLE_FAN, 0, 4);
    glBindVertexArray(0);
}

void MainMenu::drawText(const std::string &text, float x, float y, float scale,
                        float r, float g, float b, float a)
{
    if (text.empty()) return;
    float aw = FONT_COLS * FONT_CW, ah = FONT_ROWS * FONT_CH;
    float cw = (FONT_CW * scale) / screenW * 2.0f;
    float ch = (FONT_CH * scale) / screenH * 2.0f;

    std::vector<float> verts;
    float cx = x;
    for (char c : text) {
        if (c == '\n') { cx = x; y -= ch * 1.3f; continue; }
        int idx = c - 32; if (idx < 0 || idx >= FONT_CHARS) idx = 0;
        int col = idx % FONT_COLS, row = idx / FONT_COLS;
        float u0 = (col*FONT_CW)/aw, v0 = (row*FONT_CH)/ah;
        float u1 = ((col+1)*FONT_CW)/aw, v1 = ((row+1)*FONT_CH)/ah;
        verts.insert(verts.end(), {cx,y,u0,v1, cx+cw,y,u1,v1, cx+cw,y+ch,u1,v0,
                                   cx,y,u0,v1, cx+cw,y+ch,u1,v0, cx,y+ch,u0,v0});
        cx += cw;
    }

    overlayShader.setUniform1i("u_useTexture", 1);
    overlayShader.setUniform1i("u_fontAtlas", 0);
    overlayShader.setUniform4f("u_color", r, g, b, a);
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, fontTexture);
    glBindVertexArray(textVAO);
    glBindBuffer(GL_ARRAY_BUFFER, textVBO);
    glBufferSubData(GL_ARRAY_BUFFER, 0, verts.size()*sizeof(float), verts.data());
    glDrawArrays(GL_TRIANGLES, 0, verts.size()/4);
    glBindVertexArray(0);
    glBindTexture(GL_TEXTURE_2D, 0);
}

// Helper: draw centered text
void MainMenu::drawTextCentered(const std::string &text, float y, float scale,
                                float r, float g, float b, float a)
{
    float w = textWidthNDC(text, scale, screenW);
    drawText(text, -w / 2.0f, y, scale, r, g, b, a);
}

void MainMenu::update(float dt, float mouseX, float mouseY)
{
    animTime += dt;
    float mx = (mouseX / screenW) * 2.0f - 1.0f;
    float my = 1.0f - (mouseY / screenH) * 2.0f;

    auto checkHover = [&](MenuButton &btn) {
        btn.hovered = (mx >= btn.x && mx <= btn.x + btn.w &&
                       my >= btn.y && my <= btn.y + btn.h);
        float target = btn.hovered ? 1.0f : 0.0f;
        btn.hoverGlow += (target - btn.hoverGlow) * 0.12f;
    };
    checkHover(playBtn);
    checkHover(quitBtn);
}

MenuAction MainMenu::handleClick(float mouseX, float mouseY)
{
    float mx = (mouseX / screenW) * 2.0f - 1.0f;
    float my = 1.0f - (mouseY / screenH) * 2.0f;

    auto inside = [&](const MenuButton &btn) {
        return mx >= btn.x && mx <= btn.x + btn.w &&
               my >= btn.y && my <= btn.y + btn.h;
    };

    if (inside(playBtn)) return MENU_PLAY;
    if (inside(quitBtn)) return MENU_QUIT;
    return MENU_NONE;
}

